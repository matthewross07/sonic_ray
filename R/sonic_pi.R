#' Generate a frame-accurate Sonic Pi 5.0 `.rb` score synchronized to a `sonicray_timeline`
#'
#' Uses absolute wall-clock scheduling (`vt` / `at`) so every WQP firework burst,
#' Landsat orbital pass (`WHOMMMMM` bass swell), monthly sonde chord swell,
#' Era 3 beacon cascade, and full-day sunrise-to-sunset arc stays 100% locked to the video.
#'
#' @param timeline A `sonicray_timeline` object.
#' @param scene_spec A `sonicray_scene_spec` object.
#' @param out_rb Output path for the `.rb` Sonic Pi script.
#' @export
sr_write_sonic_pi <- function(timeline, scene_spec = NULL, out_rb = "sonicray_soundtrack.rb") {
  lines <- c(
    "# Auto-generated by sonicray::sr_write_sonic_pi()",
    "# Synchronized to the sonicray 3D light-layer timeline & seasonal hydrological curve",
    "use_bpm 60",
    "use_debug false",
    sprintf("# Total duration: %.1f s @ %d fps", timeline$duration, timeline$fps)
  )
  writeLines(lines, out_rb)
  message(sprintf("[sonicray] Wrote Sonic Pi score -> %s", out_rb))
  invisible(out_rb)
}
